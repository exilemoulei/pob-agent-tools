"""Offline crafting-bench knowledge for Path of Exile 1.

The bench can add one crafted modifier to an item that still has an open prefix
or suffix.  Values are lower than high-tier natural modifiers, so this module is
used to answer "what could I add to this slot", not to pretend a bench craft is
a top-tier roll.

Data is generated by ``pob_cli/scripts/update_crafting_bench.py`` from
poedb.tw (cn + us) and the PoE wiki's prefix/suffix sections.  It is committed
so the CLI never scrapes at runtime.
"""

from __future__ import annotations

import json
import re
from dataclasses import dataclass
from difflib import SequenceMatcher
from functools import lru_cache
from pathlib import Path

DATA_FILE = Path(__file__).parent / "data" / "crafting_bench.json"

SLOT_ALIASES = {
    "ring": "ring1",
    "ring1": "ring1",
    "ring2": "ring2",
    "weapon": "weapon1",
    "weapon1": "weapon1",
    "weapon2": "weapon2",
    "body": "body_armour",
    "bodyarmour": "body_armour",
    "chest": "body_armour",
}

STOP_WORDS = {"to", "the", "of", "a", "an", "your", "you", "and", "or", "per"}

AFFIX_LABELS = {"prefix": "prefix", "suffix": "suffix", "unknown": "unknown"}


@dataclass(frozen=True)
class BenchRecipe:
    text: str
    text_zh: str
    template: str
    affix: str
    slots: tuple[str, ...]
    classes: tuple[str, ...]
    values: tuple[tuple[float, float], ...]
    cost: str
    unlock: str

    @property
    def min_value(self) -> float:
        """Smallest guaranteed floor across all rolls of the mod."""
        if not self.values:
            return 0.0
        return min(low for low, _high in self.values)

    @property
    def max_value(self) -> float:
        if not self.values:
            return 0.0
        return max(high for _low, high in self.values)

    @property
    def roll_text(self) -> str:
        if not self.values:
            return "-"
        parts = []
        for low, high in self.values:
            parts.append(f"{low:g}" if low == high else f"{low:g}-{high:g}")
        return ", ".join(parts)

    def as_dict(self) -> dict:
        return {
            "text": self.text,
            "textZh": self.text_zh,
            "template": self.template,
            "affix": self.affix,
            "slots": list(self.slots),
            "values": [{"min": low, "max": high} for low, high in self.values],
            "minValue": self.min_value,
            "cost": self.cost,
            "unlock": self.unlock,
        }


@dataclass(frozen=True)
class BenchSearchResult:
    recipe: BenchRecipe
    score: float


@lru_cache(maxsize=1)
def load_data() -> dict:
    return json.loads(DATA_FILE.read_text(encoding="utf-8"))


@lru_cache(maxsize=1)
def recipes() -> tuple[BenchRecipe, ...]:
    result: list[BenchRecipe] = []
    for raw in load_data().get("recipes") or []:
        values = tuple(
            (float(value.get("min", 0)), float(value.get("max", 0)))
            for value in raw.get("values") or []
        )
        result.append(
            BenchRecipe(
                text=str(raw.get("text") or ""),
                text_zh=str(raw.get("textZh") or ""),
                template=str(raw.get("template") or ""),
                affix=str(raw.get("affix") or "unknown"),
                slots=tuple(raw.get("slots") or ()),
                classes=tuple(raw.get("classes") or ()),
                values=values,
                cost=str(raw.get("cost") or ""),
                unlock=str(raw.get("unlock") or ""),
            )
        )
    return tuple(result)


def source_metadata() -> dict:
    return dict(load_data().get("source") or {})


def slot_key(slot: str) -> str:
    value = re.sub(r"[\s_-]+", "", (slot or "").strip().lower())
    return SLOT_ALIASES.get(value, value)


def recipes_for_slot(slot: str) -> list[BenchRecipe]:
    key = slot_key(slot)
    return [recipe for recipe in recipes() if key in recipe.slots]


def _words(text: str) -> set[str]:
    return {
        word
        for word in re.findall(r"[a-z]+", text.lower())
        if len(word) >= 3 and word not in STOP_WORDS
    }


def _words_match(target: set[str], recipe: set[str]) -> bool:
    """Every requested word must be covered by a recipe word (prefix match)."""
    if not target:
        return False
    for word in target:
        if not any(
            word == other or word.startswith(other) or other.startswith(word)
            for other in recipe
        ):
            return False
    return True


def _score(recipe: BenchRecipe, target: str) -> float:
    if not target:
        return 0.0
    if target in recipe.template:
        return 1.0
    if recipe.template and recipe.template in target:
        return 0.95
    if not _words_match(_words(target), _words(recipe.template)):
        return 0.0
    return SequenceMatcher(None, target, recipe.template).ratio()


def search(slot: str, text: str, limit: int = 5) -> list[BenchSearchResult]:
    """Find bench modifiers for a slot whose template matches ``text``."""
    target = _normalize(text)
    if not target:
        return []
    scored: list[BenchSearchResult] = []
    for recipe in recipes_for_slot(slot):
        score = _score(recipe, target)
        if score >= 0.62:
            scored.append(BenchSearchResult(recipe=recipe, score=round(score, 3)))
    scored.sort(key=lambda item: (-item.score, -item.recipe.min_value, item.recipe.text))
    return scored[: max(0, limit)]


def best(slot: str, text: str) -> BenchRecipe | None:
    found = search(slot, text, limit=1)
    return found[0].recipe if found else None


def list_for_slot(slot: str, *, affix: str | None = None) -> list[BenchRecipe]:
    items = recipes_for_slot(slot)
    if affix:
        items = [recipe for recipe in items if recipe.affix == affix]
    items.sort(key=lambda recipe: (recipe.affix, -recipe.min_value, recipe.text))
    return items


def _normalize(text: str) -> str:
    from .poe_item import normalize_template

    return normalize_template(text)


def format_recipe(recipe: BenchRecipe, *, show_zh: bool = True) -> str:
    affix = AFFIX_LABELS.get(recipe.affix, recipe.affix)
    label = recipe.text
    if show_zh and recipe.text_zh and recipe.text_zh != recipe.text:
        label = f"{recipe.text} / {recipe.text_zh}"
    return f"[{affix}] {label} ({recipe.roll_text}; {recipe.cost})"
