"""Generate pob_cli/game_data/tables_han.py, the Traditional -> Simplified character fold.

Usage:
    curl -LO https://www.unicode.org/Public/UCD/latest/ucd/Unihan.zip
    python pob_cli/scripts/gen_han_fold.py Unihan.zip

Reads `kSimplifiedVariant` from Unihan_Variants.txt and keeps BMP code points only, so every entry
is a single str.translate() character. The fold is applied to both the query and the text being
searched, so a character that is also valid in Simplified text is still matched consistently.
"""

from __future__ import annotations

import argparse
import re
import sys
import zipfile
from pathlib import Path

OUT_PATH = Path(__file__).resolve().parents[1] / "src" / "pob_cli" / "game_data" / "tables_han.py"
_LINE_RE = re.compile(r"^U\+([0-9A-F]{4,6})\tkSimplifiedVariant\t(.+)$")
_VERSION_RE = re.compile(r"^# Unicode Version (\S+)")
_CHUNK = 64


def _parse(variants_text: str) -> tuple[dict[str, str], str]:
    version = "unknown"
    mapping: dict[str, str] = {}
    for line in variants_text.splitlines():
        if m := _VERSION_RE.match(line):
            version = m.group(1)
            continue
        m = _LINE_RE.match(line)
        if not m:
            continue
        src_cp = int(m.group(1), 16)
        # The first listed variant is the primary simplified form.
        dst_cp = int(m.group(2).split()[0].split("<")[0].removeprefix("U+"), 16)
        if src_cp == dst_cp or src_cp > 0xFFFF or dst_cp > 0xFFFF:
            continue
        mapping[chr(src_cp)] = chr(dst_cp)
    # Resolve chains so one translate() pass reaches the final form.
    for src in list(mapping):
        seen = {src}
        dst = mapping[src]
        while dst in mapping and dst not in seen:
            seen.add(dst)
            dst = mapping[dst]
        mapping[src] = dst
    return {s: d for s, d in mapping.items() if s != d}, version


def _chunks(text: str) -> list[str]:
    return [text[i : i + _CHUNK] for i in range(0, len(text), _CHUNK)]


def render(mapping: dict[str, str], version: str) -> str:
    keys = sorted(mapping)
    trad = "".join(keys)
    simp = "".join(mapping[k] for k in keys)
    trad_lines = "\n".join(f'    "{c}"' for c in _chunks(trad))
    simp_lines = "\n".join(f'    "{c}"' for c in _chunks(simp))
    return f'''"""Traditional -> Simplified Chinese character fold for search matching ({len(keys)} characters).

Generated by pob_cli/scripts/gen_han_fold.py from Unihan_Variants.txt (kSimplifiedVariant),
Unicode {version}. Unicode data is under the Unicode License v3. Do not edit by hand; rerun the
generator instead.
"""

_TRAD = (
{trad_lines}
)

_SIMP = (
{simp_lines}
)

HAN_FOLD = str.maketrans(_TRAD, _SIMP)
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("unihan_zip", type=Path, help="Path to Unihan.zip from unicode.org")
    args = parser.parse_args()
    with zipfile.ZipFile(args.unihan_zip) as zf:
        text = zf.read("Unihan_Variants.txt").decode("utf-8")
    mapping, version = _parse(text)
    OUT_PATH.write_text(render(mapping, version), encoding="utf-8", newline="\n")
    print(f"Wrote {len(mapping)} mappings (Unicode {version}) to {OUT_PATH}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
